"""Streamlit front end for the Health Prediction application.

Run with:  streamlit run app.py
"""
import pandas as pd
import streamlit as st

import database as db
import services

st.set_page_config(page_title="Health Prediction Records", page_icon="🩺", layout="wide")
db.init_db()

PAGES = ["Add Patient", "Records", "Edit Patient", "Delete Patient"]
FIELD_LABELS = {
    "full_name": "Full Name", "dob": "Date of Birth", "email": "Email",
    "glucose": "Glucose", "haemoglobin": "Haemoglobin", "cholesterol": "Cholesterol",
}


# ---------- small helpers ----------
def flash(message, kind="success"):
    st.session_state["flash"] = (kind, message)


def show_flash():
    kind, message = st.session_state.pop("flash", (None, None))
    if message:
        getattr(st, kind)(message)


def show_errors(errors):
    st.error("The record was not saved. Please fix the following:")
    for field_name, message in errors.items():
        st.markdown(f"- **{FIELD_LABELS.get(field_name, field_name)}:** {message}")


def render_table(patients):
    if not patients:
        st.info("No records yet.")
        return
    df = pd.DataFrame([{
        "ID": p["id"],
        "Full Name": p["full_name"],
        "Date of Birth": p["dob"].strftime("%d/%m/%Y"),
        "Email": p["email"],
        "Glucose (mg/dL)": p["glucose"],
        "Haemoglobin (g/dL)": p["haemoglobin"],
        "Cholesterol (mg/dL)": p["cholesterol"],
        "Remarks (AI)": p["remarks"],
        "Remarks source": p["remarks_source"],
    } for p in patients])
    st.dataframe(df, hide_index=True, use_container_width=True,
                 column_config={"Remarks (AI)": st.column_config.TextColumn(width="large")})
    st.caption(f"{len(patients)} record(s)")


def patient_form(key_prefix, defaults, submit_label):
    """Shared form used by Add and Edit. Returns (submitted, data)."""
    with st.form(key_prefix):
        c1, c2 = st.columns(2)
        data = {
            "full_name": c1.text_input("Full Name", defaults["full_name"], key=f"{key_prefix}_name"),
            "dob": c2.text_input("Date of Birth (dd/mm/yyyy)", defaults["dob"], key=f"{key_prefix}_dob"),
            "email": c1.text_input("Email Address", defaults["email"], key=f"{key_prefix}_email"),
        }
        c3, c4, c5 = st.columns(3)
        data["glucose"] = c3.text_input("Glucose (mg/dL)", defaults["glucose"], key=f"{key_prefix}_glu")
        data["haemoglobin"] = c4.text_input("Haemoglobin (g/dL)", defaults["haemoglobin"], key=f"{key_prefix}_hb")
        data["cholesterol"] = c5.text_input("Cholesterol (mg/dL)", defaults["cholesterol"], key=f"{key_prefix}_chol")
        submitted = st.form_submit_button(submit_label, type="primary")
    return submitted, data


def record_label(p):
    return f"#{p['id']} - {p['full_name']} ({p['email']})"


# ---------- pages ----------
def page_add():
    st.subheader("Add a patient")
    st.caption("Remarks are generated by the AI after the data passes validation.")
    version = st.session_state.setdefault("add_version", 0)
    empty = {k: "" for k in FIELD_LABELS}
    submitted, data = patient_form(f"add_{version}", empty, "Save and predict")
    if submitted:
        with st.spinner("Validating and calling the AI service..."):
            result = services.add_patient(data)
        if result.ok:
            patient = services.get_patient(result.patient_id)
            flash(f"Saved {patient['full_name']}. Remarks: {patient['remarks']}")
            st.session_state["add_version"] += 1  # new widget keys -> blank form
            st.rerun()
        else:
            show_errors(result.errors)


def page_records():
    st.subheader("All records")
    render_table(services.list_patients())


def page_edit():
    st.subheader("Edit a patient")
    patients = services.list_patients()
    if not patients:
        st.info("No records to edit.")
        return
    chosen = st.selectbox("Select a record", patients, format_func=record_label)
    version = st.session_state.setdefault("edit_version", 0)
    defaults = {
        "full_name": chosen["full_name"],
        "dob": chosen["dob"].strftime("%d/%m/%Y"),
        "email": chosen["email"],
        "glucose": f"{chosen['glucose']:g}",
        "haemoglobin": f"{chosen['haemoglobin']:g}",
        "cholesterol": f"{chosen['cholesterol']:g}",
    }
    submitted, data = patient_form(f"edit_{chosen['id']}_{version}", defaults, "Update record")
    if submitted:
        result = services.update_patient(chosen["id"], data)
        if result.ok:
            flash(f"Updated record #{chosen['id']}.")
            st.session_state["edit_version"] += 1
            st.rerun()
        else:
            show_errors(result.errors)


def page_delete():
    st.subheader("Delete a patient")
    patients = services.list_patients()
    if not patients:
        st.info("No records to delete.")
        return
    chosen = st.selectbox("Select a record", patients, format_func=record_label)
    confirm = st.checkbox(f"Yes, permanently delete record #{chosen['id']} ({chosen['full_name']})")
    if st.button("Delete record", type="primary", disabled=not confirm):
        services.delete_patient(chosen["id"])
        flash(f"Deleted record #{chosen['id']} ({chosen['full_name']}).")
        st.rerun()
    st.divider()
    st.markdown("**Current records**")
    render_table(patients)


# ---------- layout ----------
st.title("🩺 Health Prediction Records")
st.sidebar.header("Menu")
page = st.sidebar.radio("Go to", PAGES, key="page", label_visibility="collapsed")
st.sidebar.caption("AI remarks are a screening aid, not a medical diagnosis.")
show_flash()

{"Add Patient": page_add, "Records": page_records,
 "Edit Patient": page_edit, "Delete Patient": page_delete}[page]()
